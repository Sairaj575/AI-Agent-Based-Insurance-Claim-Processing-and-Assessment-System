
from schemas.claim import InsuranceClaim
from workflow.graph import claim_workflow


# 1. Create an insurance claim
claim = InsuranceClaim(
    claim_id="CLM1001",
    customer_name="Rahul",
    claim_amount=90000,
    policy_amount=100000,
    policy_active=True,
    documents=[
        "identity_proof",
        "medical_bill",
        "hospital_report"
    ],
    required_documents=[
        "identity_proof",
        "medical_bill",
        "hospital_report"
    ],
    incident_description="Hospitalization due to accident"
)


# 2. Prepare initial workflow state
initial_state = {
    "claim": claim
}


# 3. Execute the complete LangGraph workflow
print("\n========== INSURANCE CLAIM PROCESSING ==========")

result = claim_workflow.invoke(initial_state)


# 4. Display document verification result
print("\n--- DOCUMENT VERIFICATION ---")
print("Status:", result["document_result"]["document_status"])
print("Missing Documents:", result["document_result"]["missing_documents"])


# 5. Display eligibility and risk result
print("\n--- ELIGIBILITY & RISK ASSESSMENT ---")
print("Eligibility:", result["eligibility_result"]["eligibility"])
print("Risk Score:", result["eligibility_result"]["risk_score"])
print("Risk Level:", result["eligibility_result"]["risk_level"])
print("Risk Reasons:", result["eligibility_result"]["risk_reasons"])


# 6. Display AI-generated claim summary
print("\n--- CLAIM SUMMARY ---")
print(result["summary_result"]["claim_summary"])
print("Summary Generated By:", result["summary_result"]["status"])


# 7. Display final decision
print("\n--- FINAL DECISION ---")
print("Decision:", result["decision"])
print("Reason:", result["decision_reason"])
print("Final Status:", result["final_status"])


print("\n========== PROCESSING COMPLETED ==========")
